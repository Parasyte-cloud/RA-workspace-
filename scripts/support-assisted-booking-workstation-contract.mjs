import fs from 'node:fs'

const route =
  fs.readFileSync(
    'src/modules/SupportWorkspaceRoute.tsx',
    'utf8'
  )

const team =
  fs.readFileSync(
    'src/modules/DepartmentTeamWorkspace.tsx',
    'utf8'
  )

const ui =
  fs.readFileSync(
    'src/modules/SupportAssistedBookingPanel.tsx',
    'utf8'
  )

const client =
  fs.readFileSync(
    'src/lib/ridearrivoSupport.ts',
    'utf8'
  )

const edge =
  fs.readFileSync(
    'supabase/functions/ridearrivo-support/index.ts',
    'utf8'
  )

let passed = 0
let failed = 0

function check(name, condition) {
  if (condition) {
    console.log(`PASS: ${name}`)
    passed += 1
  } else {
    console.log(`FAIL: ${name}`)
    failed += 1
  }
}

console.log(
  'Support workstation assisted-booking contract:'
)

check(
  'Support route imports dedicated assisted-booking panel',
  route.includes(
    "import SupportAssistedBookingPanel from './SupportAssistedBookingPanel'"
  )
)

check(
  'assisted booking is rendered as workstation content',
  route.includes(
    'workstationContent={'
  ) &&
  route.includes(
    '<SupportAssistedBookingPanel/>'
  )
)

check(
  'SupportTeamWorkspace accepts workstationContent',
  /SupportTeamWorkspace\([\s\S]{0,400}workstationContent\?:ReactNode/.test(
    team
  )
)

check(
  'SupportTeamWorkspace forwards workstationContent',
  /SupportTeamWorkspace[\s\S]{0,4000}workstationContent=\{workstationContent\}/.test(
    team
  )
)

check(
  'browser client exposes assisted-booking mutation helper',
  client.includes(
    'createRideArrivoAssistedBooking'
  )
)

check(
  'browser client calls only the existing Support Edge Function',
  /createRideArrivoAssistedBooking[\s\S]{0,3000}functions\.invoke\([\s\S]{0,100}['"]ridearrivo-support['"]/.test(
    client
  )
)

check(
  'browser client selects explicit mutation action',
  client.includes(
    "action: 'createAssistedBooking'"
  )
)

check(
  'assisted-booking UI contains no customer password control',
  !/type\\s*=\\s*["']password["']/i.test(ui) &&
  !/name\\s*=\\s*["'](?:customer_?)?password["']/i.test(ui) &&
  !/customerPassword\\s*[=:]/i.test(ui)
)

check(
  'customer cancellation-policy confirmation is required',
  ui.includes(
    'agreedCancellationPolicy'
  ) &&
  /Cancellation & Refund/.test(
    ui
  )
)

check(
  'UI explicitly preserves customer payment boundary',
  ui.includes(
    'requiresCustomerPayment'
  ) &&
  /Support does not collect or enter[\s\S]{0,120}card details/.test(
    ui
  )
)

check(
  'Edge Function recognises only explicit assisted-booking action',
  edge.includes(
    'body.action ==='
  ) &&
  edge.includes(
    '"createAssistedBooking"'
  )
)

check(
  'assisted-booking mutation is Support/Admin only',
  edge.includes(
    'new Set(["support", "admin"])'
  ) &&
  edge.includes(
    'assistedBookingRoles.has('
  )
)

check(
  'Workspace actor signing secret is server-side',
  edge.includes(
    'RIDEARRIVO_WORKSPACE_SERVICE_SECRET'
  )
)

check(
  'Workspace actor signing secret requires minimum length',
  /serviceSecret\.length < 32/.test(
    edge
  )
)

check(
  'actor envelope uses HS256-compatible HMAC SHA-256',
  edge.includes(
    'name: "HMAC"'
  ) &&
  edge.includes(
    'hash: "SHA-256"'
  ) &&
  edge.includes(
    'alg: "HS256"'
  )
)

check(
  'actor token uses required issuer and audience',
  edge.includes(
    'iss: "ridearrivo-workspace"'
  ) &&
  edge.includes(
    'aud: "arrivo-backend"'
  )
)

check(
  'actor identity derives from verified employee profile',
  edge.includes(
    'String(profile.id || "")'
  ) &&
  edge.includes(
    'String(profile.email || "")'
  )
)

check(
  'gateway generates actor request id server-side',
  edge.includes(
    'const actorRequestId ='
  ) &&
  edge.includes(
    'crypto.randomUUID()'
  )
)

check(
  'trusted actor header is generated by Edge Function',
  edge.includes(
    '"x-ridearrivo-workspace-actor":'
  ) &&
  edge.includes(
    'workspaceActor'
  )
)

check(
  'only dedicated assisted-booking endpoint receives POST',
  edge.includes(
    '`${backendUrl}/api/support/assisted-bookings`'
  ) &&
  /performMutation[\s\S]{0,800}method: "POST"/.test(
    edge
  )
)

check(
  'booking payload is allow-listed before forwarding',
  edge.includes(
    'sanitizeAssistedBooking'
  ) &&
  edge.includes(
    'assistedBookingKeys'
  ) &&
  edge.includes(
    'JSON.stringify('
  ) &&
  edge.includes(
    'booking,'
  )
)

check(
  'ordinary Support resource proxy remains GET-only',
  /const fetchResource[\s\S]{0,500}method: "GET"/.test(
    edge
  )
)

check(
  'existing Support workstation authorization remains enforced',
  edge.includes(
    '.eq("workstation", "support")'
  ) &&
  edge.includes(
    'hasSupportWorkstation'
  )
)

check(
  'backend service-account token remains required upstream',
  edge.includes(
    'getBackendToken('
  ) &&
  edge.includes(
    'Authorization:'
  )
)

console.log(
  `SUPPORT_ASSISTED_WORKSTATION_CONTRACT_PASS=${passed}`
)

console.log(
  `SUPPORT_ASSISTED_WORKSTATION_CONTRACT_FAIL=${failed}`
)

if (failed > 0) {
  process.exitCode = 1
}
