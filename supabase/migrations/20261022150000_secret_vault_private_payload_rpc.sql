begin;

-- The private Vault schema remains unavailable through normal browser/Data API
-- table access. Encrypted payload I/O is performed through narrowly scoped,
-- service-role-only SECURITY DEFINER functions.

create or replace function public.vault_store_encrypted_payload(
  target_item uuid,
  ciphertext_base64 text,
  iv_base64 text,
  payload_aad text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
declare
  decoded_ciphertext bytea;
  decoded_iv bytea;
begin
  if target_item is null then
    raise exception 'Vault item is required';
  end if;

  if ciphertext_base64 is null or ciphertext_base64 = '' then
    raise exception 'Encrypted payload is required';
  end if;

  if iv_base64 is null or iv_base64 = '' then
    raise exception 'Encryption IV is required';
  end if;

  if payload_aad is null
     or char_length(payload_aad) < 1
     or char_length(payload_aad) > 512 then
    raise exception 'Invalid payload AAD';
  end if;

  begin
    decoded_ciphertext := decode(ciphertext_base64, 'base64');
    decoded_iv := decode(iv_base64, 'base64');
  exception
    when others then
      raise exception 'Invalid encrypted payload encoding';
  end;

  -- AES-GCM IV generated by the Edge Function is 96 bits.
  if octet_length(decoded_iv) <> 12 then
    raise exception 'Invalid encryption IV';
  end if;

  -- Plaintext is capped at 15 MiB. AES-GCM adds a 16-byte authentication tag.
  if octet_length(decoded_ciphertext) < 17
     or octet_length(decoded_ciphertext) > 15728656 then
    raise exception 'Invalid encrypted payload size';
  end if;

  insert into private.secret_vault_payloads (
    item_id,
    ciphertext,
    iv,
    aad
  )
  values (
    target_item,
    decoded_ciphertext,
    decoded_iv,
    payload_aad
  );
end;
$$;

create or replace function public.vault_read_encrypted_payload(
  target_item uuid
)
returns table (
  ciphertext_base64 text,
  iv_base64 text,
  aad text
)
language sql
stable
security definer
set search_path = pg_catalog, public, private
as $$
  select
    encode(p.ciphertext, 'base64') as ciphertext_base64,
    encode(p.iv, 'base64') as iv_base64,
    p.aad
  from private.secret_vault_payloads p
  where p.item_id = target_item;
$$;

revoke all
on function public.vault_store_encrypted_payload(uuid, text, text, text)
from public, anon, authenticated;

revoke all
on function public.vault_read_encrypted_payload(uuid)
from public, anon, authenticated;

grant execute
on function public.vault_store_encrypted_payload(uuid, text, text, text)
to service_role;

grant execute
on function public.vault_read_encrypted_payload(uuid)
to service_role;

-- Preserve the core boundary explicitly.
revoke all
on table private.secret_vault_payloads
from public, anon, authenticated;

commit;
